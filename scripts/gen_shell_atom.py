"""
Writes src/game/atom/shellModel.generated.ts with RDKit, for the ShellAtom figure
(src/game/atom/ShellAtom.tsx) and its test (src/game/test/shellAtom.test.ts).

Three tables, all read from RDKit, none typed by hand:

  OUTER_ELECTRONS  RDKit's periodic table count of outer (valence) electrons,
                   Chem.GetPeriodicTable().GetNOuterElecs(Z), for every element
                   the shell rule in shellModel.ts supports. The test checks the
                   rule's last shell against this, element by element.
  ATOM_PRESETS     The three atoms the Unit 0 "Bonds and formal charge" scene
                   lets a student explore: the centre atom of each SMILES, its
                   bond partners and bond orders (hydrogens made explicit), its
                   lone pairs and RDKit's formal charge.
  FORMAL_CASES     More centre atoms, same reading, so the test can check the
                   card's formal charge count (valence minus owned) against
                   RDKit's formal charge on species beyond the three presets.

Lone pairs = (outer electrons - formal charge - sum of bond orders) / 2, which
is the electron count RDKit's own valence model implies; the script fails if it
is not a whole, non-negative number.

Run: python scripts/gen_shell_atom.py   (then the test byte-checks nothing; it
compares values, so rerun only when a table changes).
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

from rdkit import Chem, rdBase

OUT = Path(__file__).resolve().parent.parent / "src" / "game" / "atom" / "shellModel.generated.ts"

# Z 1-20 (the first twenty, through calcium) plus the two heavier halogens the
# course uses (bromide and iodide leaving groups, Br2 and I2 additions).
SUPPORTED_Z = list(range(1, 21)) + [35, 53]

PRESETS = [
    # id, label, SMILES, the centre atom's index in that SMILES
    ("c-methane", "C in methane", "C", 0),
    ("n-ammonium", "N in ammonium", "[NH4+]", 0),
    ("o-hydroxide", "O in hydroxide", "[OH-]", 0),
]

CASES = [
    ("water", "O", 0),
    ("ammonia", "N", 0),
    ("hydronium", "[OH3+]", 0),
    ("amide ion", "[NH2-]", 0),
    ("methyl cation", "[CH3+]", 0),
    ("methyl anion", "[CH3-]", 0),
    ("borohydride", "[BH4-]", 0),
    ("carbonyl O of formaldehyde", "C=O", 1),
    ("carbonyl C of formaldehyde", "C=O", 0),
    ("nitrile N of acetonitrile", "CC#N", 2),
    ("alkoxide O of methoxide", "C[O-]", 1),
    ("bromide", "[Br-]", 0),
    ("chloride", "[Cl-]", 0),
]


def fail(msg: str) -> None:
    print(f"gen_shell_atom: {msg}", file=sys.stderr)
    sys.exit(1)


def read_centre(smi: str, idx: int) -> dict:
    m = Chem.MolFromSmiles(smi)
    if m is None:
        fail(f"RDKit cannot parse {smi}")
    mh = Chem.AddHs(m)
    a = mh.GetAtomWithIdx(idx)
    pt = Chem.GetPeriodicTable()
    outer = pt.GetNOuterElecs(a.GetAtomicNum())
    bonds = []
    for b in a.GetBonds():
        other = b.GetOtherAtom(a)
        order = b.GetBondTypeAsDouble()
        if order not in (1.0, 2.0, 3.0):
            fail(f"{smi}: bond order {order} is not 1, 2 or 3")
        bonds.append({"to": other.GetSymbol(), "order": int(order)})
    # Heavier partners first, then by order, so the drawing is stable.
    bonds.sort(key=lambda x: (x["to"] == "H", -x["order"], x["to"]))
    fc = a.GetFormalCharge()
    bonding = sum(x["order"] for x in bonds)
    nonbonding = outer - fc - bonding
    if nonbonding < 0 or nonbonding % 2:
        fail(f"{smi} atom {idx}: {nonbonding} nonbonding electrons is not a whole number of pairs")
    if a.GetNumRadicalElectrons():
        fail(f"{smi} atom {idx}: radicals are not drawn")
    return {
        "symbol": a.GetSymbol(),
        "z": a.GetAtomicNum(),
        "bonds": bonds,
        "lonePairs": nonbonding // 2,
        "formalCharge": fc,
    }


def main() -> None:
    pt = Chem.GetPeriodicTable()
    outer = {str(z): {"symbol": pt.GetElementSymbol(z), "outer": pt.GetNOuterElecs(z)} for z in SUPPORTED_Z}
    presets = []
    for pid, label, smi, idx in PRESETS:
        presets.append({"id": pid, "label": label, "smiles": Chem.CanonSmiles(smi), **read_centre(smi, idx)})
    cases = [{"name": n, "smiles": Chem.CanonSmiles(s), **read_centre(s, i)} for n, s, i in CASES]

    body = (
        "/**\n"
        " * GENERATED by scripts/gen_shell_atom.py with RDKit "
        f"{rdBase.rdkitVersion}. Do not edit by hand:\n"
        " * change the script and rerun it. See the script for what each table is.\n"
        " */\n"
        'import type { AtomBonding } from "./shellModel";\n\n'
        "/** RDKit GetNOuterElecs by atomic number, for every element the shell rule supports. */\n"
        f"export const RDKIT_OUTER_ELECTRONS: Readonly<Record<string, {{ readonly symbol: string; readonly outer: number }}>> = {json.dumps(outer, indent=2)};\n\n"
        "export interface AtomPreset extends AtomBonding {\n"
        "  readonly id: string;\n"
        "  readonly label: string;\n"
        "  readonly smiles: string;\n"
        "  readonly symbol: string;\n"
        "  readonly z: number;\n"
        "  /** RDKit's formal charge on the centre atom. */\n"
        "  readonly formalCharge: number;\n"
        "}\n\n"
        "/** The atoms the Unit 0 bonding scene lets a student explore. */\n"
        f"export const ATOM_PRESETS: readonly AtomPreset[] = {json.dumps(presets, indent=2)};\n\n"
        "/** More centre atoms read the same way, for the formal charge test. */\n"
        f"export const FORMAL_CASES: readonly (AtomBonding & {{ readonly name: string; readonly smiles: string; readonly symbol: string; readonly z: number; readonly formalCharge: number }})[] = {json.dumps(cases, indent=2)};\n"
    )
    OUT.write_text(body, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
