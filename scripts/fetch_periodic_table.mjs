/**
 * Fetches the periodic table from PubChem and writes it, unchanged, into
 * src/game/tabs/periodic/pubchemElements.ts.
 *
 * Source: PubChem Periodic Table, National Center for Biotechnology
 * Information (NCBI), https://pubchem.ncbi.nlm.nih.gov/periodic-table/
 * REST endpoint: https://pubchem.ncbi.nlm.nih.gov/rest/pug/periodictable/JSON
 * PubChem data from NCBI is a US government work and in the public domain.
 *
 * Run:   node scripts/fetch_periodic_table.mjs
 * or, with a copy you already downloaded (the endpoint can take a minute):
 *        node scripts/fetch_periodic_table.mjs path/to/periodictable.json
 *
 * The values are written as PubChem's own strings, row for row. Parsing them
 * into numbers happens in elements.ts, so this file is always a faithful copy
 * of the source and a diff after a re-run shows exactly what PubChem changed.
 */

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const URL = "https://pubchem.ncbi.nlm.nih.gov/rest/pug/periodictable/JSON";
const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.join(here, "..", "src", "game", "tabs", "periodic", "pubchemElements.ts");

async function load() {
  const local = process.argv[2];
  if (local !== undefined) return JSON.parse(await readFile(local, "utf8"));
  const response = await fetch(URL);
  if (!response.ok) throw new Error(`PubChem answered ${response.status}`);
  return response.json();
}

const data = await load();
const columns = data.Table.Columns.Column;
const rows = data.Table.Row.map((row) => row.Cell);

if (rows.length !== 118) throw new Error(`expected 118 elements, got ${rows.length}`);
rows.forEach((cells, index) => {
  if (cells.length !== columns.length) throw new Error(`row ${index + 1} has ${cells.length} cells`);
  if (Number(cells[0]) !== index + 1) throw new Error(`row ${index + 1} is element ${cells[0]}`);
});

const lines = [
  "/**",
  " * GENERATED by scripts/fetch_periodic_table.mjs. Do not edit by hand; re-run the script.",
  " *",
  " * Source: PubChem Periodic Table, NCBI (public domain),",
  ` * ${URL}`,
  ` * Fetched ${new Date().toISOString().slice(0, 10)}. Values are PubChem's own strings.`,
  " * Units, per PubChem: AtomicMass u, AtomicRadius pm (van der Waals), IonizationEnergy eV,",
  " * ElectronAffinity eV, MeltingPoint and BoilingPoint K, Density g/cm3.",
  " */",
  "",
  `export const PUBCHEM_COLUMNS = ${JSON.stringify(columns)} as const;`,
  "",
  "export const PUBCHEM_ROWS: readonly (readonly string[])[] = [",
  ...rows.map((cells) => `  ${JSON.stringify(cells)},`),
  "];",
  "",
];

await writeFile(out, lines.join("\n"), "utf8");
console.log(`wrote ${rows.length} elements to ${path.relative(process.cwd(), out)}`);
