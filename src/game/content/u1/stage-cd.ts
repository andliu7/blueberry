/** A generated figure by key. A typo throws at import, which is an authoring defect. */
function fig(key: string): Figure {
  const found = CD_FIGURES[key];
  if (found === undefined) throw new Error(`stage-cd: no generated figure "${key}"`);
  return found;
}

function structure(key: string, name: string): McqVisual {
  return { kind: "structure", figure: fig(key), name };
}

function pair(aKey: string, aName: string, bKey: string, bName: string): McqVisual {
  return { kind: "pair", a: { figure: fig(aKey), name: aName }, b: { figure: fig(bKey), name: bName } };
}

function scheme(leftKey: string, leftName: string, over?: string, under?: string): McqVisual {
  return {
    kind: "scheme",
    scheme: {
      left: fig(leftKey),
      leftName,
      ...(over === undefined ? {} : { over }),
      ...(under === undefined ? {} : { under }),
    },
  };
}

/** Option tiles: option id to [figure key, caption]. */
function tiles(spec: Readonly<Record<string, readonly [string, string]>>): Readonly<Record<string, NamedFigure>> {
  const out: Record<string, NamedFigure> = {};
  for (const [id, [key, name]] of Object.entries(spec)) out[id] = { figure: fig(key), name };
  return out;
}

