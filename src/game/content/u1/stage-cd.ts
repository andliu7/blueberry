interface Opt {
  readonly id: string;
  readonly text: string;
  readonly why: string;
}

interface Spec {
  readonly id: string;
  readonly node: string;
  readonly concept: ConceptId;
  /** Further concepts, after `concept`. */
  readonly alsoConcepts?: readonly ConceptId[];
  readonly levels: readonly MasteryLevel[];
  readonly prompt: string;
  readonly brief?: string;
  readonly correct: string;
  readonly options: readonly Opt[];
  readonly explanation: string;
  readonly conditions?: string;
  readonly provenance: string;
  readonly visual: McqVisual;
  readonly tiles?: Readonly<Record<string, NamedFigure>>;
}

const VIDEO: readonly MasteryLevel[] = [0, 1, 2];
const PRACTICE: readonly MasteryLevel[] = [1, 2];
const QUIZ: readonly MasteryLevel[] = [2];

function entry(s: Spec): PoolEntry {
  const beat: McqBeat = {
    kind: "mcq",
    id: s.id,
    node: s.node,
    conceptIds: [s.concept, ...(s.alsoConcepts ?? [])],
    levels: s.levels,
    prompt: s.prompt,
    ...(s.brief === undefined ? {} : { brief: s.brief }),
    correctOptionId: s.correct,
    options: s.options,
  };
  return {
    id: s.id,
    item: { kind: "mcq", beat },
    explanation: s.explanation,
    ...(s.conditions === undefined ? {} : { conditions: s.conditions }),
    provenance: s.provenance,
    placeholder: true,
  };
}

