/**
 * How hard a pathway node is, MEASURED off the content it launches.
 *
 * WHY THIS FILE EXISTS. The sheet used to fill its pips from a table keyed by
 * node kind: spine 2, branch 2, gate 3, boss 4. Every spine and branch node in
 * the product therefore showed the same two pips, which is the chip's own kind
 * restated as a number. CLAUDE.md's rule is that anything shown to a student is
 * derived from data and never asserted, and a difficulty row that ranks nothing
 * is an assertion with dots on it.
 *
 * THE RULE, and it is the only one:
 *
 *   A MOVE is one thing the node's content grades. Difficulty is how many
 *   moves the node asks for, banded into the four pips.
 *
 *     a mechanism arrow                  1 move   (chem-core grades arrow by arrow)
 *     a fork choice inside a sequence    1 move
 *     a resonance arrow                  1 move
 *     any other authored beat            1 move   (one MCQ set, one match board,
 *                                                  one ladder, one synthesis gap
 *                                                  set: each is one graded surface)
 *
 *   A node whose lesson plan is empty has no content behind it, so it has NO
 *   difficulty and the sheet draws no pips. Absent is not "average".
 *
 * WHY A TABLE AND NOT A CALL. Counting arrows means importing the trainer
 * corpus, and app/courseUniverse.generated.ts already records what that costs:
 * "importing the corpus there put the whole authored curriculum in front of
 * every student". The pathway tab is entry-chunk code, so the measurement is
 * committed here as numbers and test/nodeDifficulty.test.ts RECOMPUTES it from
 * the real content on every run and fails if the two drift. The table is
 * evidence, not authorship: nobody chooses a row, the test regenerates it.
 */

